/* =====================================================================
 * tileset.js — Cainos 素材的座標對照表
 * =====================================================================
 *
 * 【這份表的由來，以及為什麼多數物件用像素座標】
 *
 * 一開始我用「格線對齊」的方式裁切物件，結果反覆出現破圖：棕色描邊斷裂、
 * 木桶上緣被切掉、憑空出現一片樹葉和它的影子。
 *
 * 原因是這些圖集**不是**每格一個物件。作者是把物件緊密排在一起，
 * 相鄰兩個物件常常共用同一個格子欄位。例如：
 *   · 第一棵樹佔 x24-136，但格線在 x128 就切了 —— 被切下來的 x128-136
 *     正好落在第二棵樹的框裡，於是變成一片浮空的葉子。
 *   · 木桶實際是 y153-188，從 row 5（y160）切下去，上緣就少了 7 像素。
 *
 * 所以除了真正的「地磚」（草地、石地板、牆）以外，所有物件都改用
 * **連通區域分析**（把相連的不透明像素視為同一個物件）算出的像素矩形。
 * 這是量出來的，不是目視或按格數推的。
 *
 * 物件的欄位意義：
 *   sx, sy, sw, sh   圖集上的像素矩形
 *   w, h             它在地圖上佔幾格（繪製時於此範圍內置中、貼齊底部）
 * ===================================================================== */

